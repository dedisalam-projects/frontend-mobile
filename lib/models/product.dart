class Product {
  final String id;
  final String code;
  final String name;
  final String description;
  final double price;
  final int quantity;
  final String inventoryStatus;
  final String category;
  final String image;
  final double rating;

  Product({
    required this.id,
    required this.code,
    required this.name,
    required this.description,
    required this.price,
    required this.quantity,
    required this.inventoryStatus,
    required this.category,
    required this.image,
    required this.rating,
  });
}
